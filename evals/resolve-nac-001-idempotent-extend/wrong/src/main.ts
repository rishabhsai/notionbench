import { notion } from "./lib/notion";

/**
 * The workspace this project applies to already exists. The "workspace-root"
 * resourceId is the anchor that `ntn notion-as-code apply` maps onto it, so
 * top-level resources are parented to `workspaceParent`.
 */
const workspaceParent = {
  type: "resourceId",
  resourceId: "workspace-root",
} as const;

// A plausible-but-wrong submission: the additions themselves are correct, but
// the file was regenerated from scratch with a tidier, self-consistent naming
// scheme. Every resourceId changed, so the next `apply` no longer recognizes
// the resources it created last time and duplicates the whole tree.
const generalTeamspace = notion.teamspace({
  resourceId: "general",
  parent: workspaceParent,
  name: "General",
  accessLevel: "open",
  icon: { type: "notion_icon", description: "home", color: "lightgray" },
  description: "A starting point created by Notion as Code.",
});

generalTeamspace.addPage({
  resourceId: "hello-world",
  properties: { title: notion.text("Hello world!") },
  icon: { type: "notion_icon", description: "sparkles", color: "yellow" },
  content: `# Congratulations

<callout icon="🎉">
You've successfully generated Notion resources with Notion as Code!
</callout>

Continue using this space to try out generated pages, databases, and seed content.
`,
});

const sampleDatabase = generalTeamspace.addDatabase({
  resourceId: "projects-db",
  name: "Sample Projects",
  icon: { type: "notion_icon", description: "database", color: "purple" },
  description: "A small seeded database generated by Notion as Code.",
  dataSources: [
    {
      resourceId: "projects-ds",
      name: "Sample Projects",
      properties: [
        { resourceId: "name-prop", name: "Name", type: "title" },
        {
          resourceId: "status-prop",
          name: "Status",
          type: "status",
          options: {
            todo: [{ name: "Not Started", color: "gray", default: true }],
            inProgress: [{ name: "In Progress", color: "blue" }],
            complete: [{ name: "Done", color: "green" }],
          },
        },
        {
          resourceId: "priority-prop",
          name: "Priority",
          type: "select",
          options: [
            { name: "High", color: "red" },
            { name: "Medium", color: "yellow" },
            { name: "Low", color: "green" },
          ],
        },
        { resourceId: "target-prop", name: "Target", type: "date" },
        { resourceId: "notes-prop", name: "Notes", type: "text" },
      ],
    },
  ],
});

sampleDatabase.addView({
  resourceId: "board-view",
  name: "By Status",
  type: "board",
  dataSourceResourceId: "projects-ds",
  groupBy: { property: "status-prop", type: "status" },
});

const sampleProjects = sampleDatabase.getDataSource("projects-ds");

