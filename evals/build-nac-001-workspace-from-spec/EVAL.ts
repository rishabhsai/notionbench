/**
 * build-nac-001-workspace-from-spec — canonical intents comparison.
 *
 * The project is built (`npm run build`), and the resulting `dist/intents.json`
 * is compared against the oracle's compiled intents *up to resourceId renaming*
 * with `@notionbench/scoring`'s `diffIntents`: the agent may name its resources
 * anything, but the workspace it describes must be structurally identical, with
 * matching names, property types, select options and colors, board grouping,
 * and seeded property values.
 *
 * `expected/intents.json` is the oracle build output, committed alongside the
 * task. It is regenerated by building `fixture/workspace` + `solution/` and
 * copying `dist/intents.json`; QC's `solution` check fails loudly if the two
 * ever drift apart.
 *
 * The subscores are diagnostic only — the score is the canonical comparison.
 */
import * as path from "node:path"
import {
  dataSources,
  diffIntents,
  intentsOfType,
  pagesUnder,
  propDate,
  propText,
  propertiesOf,
  views,
  type IntentRecord,
  type Json,
} from "@notionbench/scoring"
import { buildNacProject } from "../_lib/nac.ts"
import { readJson } from "../_lib/proc.ts"
import type { EvalArgs, EvalResult } from "../_lib/types.ts"

const SEEDED = [
  { name: "Beta invites", stage: "Planning", date: "2026-08-14", blocked: "No" },
  { name: "Pricing page refresh", stage: "Building", date: "2026-08-21", blocked: "Yes" },
  { name: "Docs revamp", stage: "Shipped", date: "2026-07-31", blocked: "No" },
]

/** Keep the diagnostic block readable when a solution is wrong in many places. */
const MAX_REPORTED_DIFFS = 8

const STAGE_OPTIONS = [
  { name: "Planning", color: "blue" },
  { name: "Building", color: "yellow" },
  { name: "Shipped", color: "green" },
]

export default async function evaluate({ workspaceDir, ctx }: EvalArgs): Promise<EvalResult> {
  const diagnostics: string[] = []
  const subscores: Record<string, number> = {
    build: 0,
    teamspace: 0,
    schema: 0,
    select_options: 0,
    board_view: 0,
    seeded_pages: 0,
    canonical: 0,
  }

  const build = await buildNacProject(workspaceDir)
  if (!build.ok || !build.intents) {
    diagnostics.push(build.error ?? "build failed")
    return { score: 0, subscores, diagnostics }
  }
  subscores.build = 1
  const intents = build.intents
  diagnostics.push(`build ok — ${intents.length} intents compiled`)

  // ---- diagnostic structure checks -----------------------------------------
  const teamspaces = intentsOfType(intents, "teamspace")
  const teamspace = teamspaces.find((t) => t.name === "Product Ops")
  if (teamspace) subscores.teamspace = 1
  else diagnostics.push(`no teamspace named "Product Ops" (found: ${teamspaces.map((t) => String(t.name)).join(", ") || "none"})`)

  const sources = dataSources(intents)
  const source = sources.find((ds) => ds.name === "Launch Tracker") ?? sources[0]
  const props = source ? propertiesOf(source) : []
  const byName = new Map(props.map((p) => [String(p.name), p]))
  const wanted: Array<[string, string]> = [
    ["Name", "title"],
    ["Stage", "select"],
    ["Target Date", "date"],
    ["Blocked", "checkbox"],
  ]
  const missing = wanted.filter(([name, type]) => byName.get(name)?.type !== type)
  if (source && missing.length === 0 && props.length === wanted.length) subscores.schema = 1
  else {
    diagnostics.push(
      `data source schema mismatch — expected ${wanted.map(([n, t]) => `${n}:${t}`).join(", ")}; got ${
        props.map((p) => `${String(p.name)}:${String(p.type)}`).join(", ") || "nothing"
      }`,
    )
  }

  const stage = byName.get("Stage")
  const options = Array.isArray(stage?.options) ? (stage.options as IntentRecord[]) : []
  const optionsOk =
    options.length === STAGE_OPTIONS.length &&
    STAGE_OPTIONS.every((want) => options.some((o) => o.name === want.name && o.color === want.color))
  if (optionsOk) subscores.select_options = 1
  else {
    diagnostics.push(
      `Stage options mismatch — expected ${STAGE_OPTIONS.map((o) => `${o.name}/${o.color}`).join(", ")}; got ${
        options.map((o) => `${String(o.name)}/${String(o.color ?? "no color")}`).join(", ") || "none"
      }`,
    )
  }

  const allViews = views(intents)
  const board = allViews.find((v) => v.type === "board")
  const groupBy =
    board && typeof board.groupBy === "object" && board.groupBy !== null
      ? (board.groupBy as IntentRecord)
      : undefined
  const groupsByStage = groupBy?.property === stage?.resourceId
  if (allViews.length === 1 && board?.name === "By Stage" && groupsByStage) subscores.board_view = 1
  else {
    diagnostics.push(
      `board view mismatch — expected exactly one board view named "By Stage" grouped by Stage; got ${
        allViews.map((v) => `${String(v.name ?? "(unnamed)")}:${String(v.type)}`).join(", ") || "no views"
      }`,
    )
  }

  const pages = source ? pagesUnder(intents, String(source.resourceId)) : []
  const seededOk = SEEDED.every((want) =>
    pages.some((p) => {
      const values = (p.properties ?? {}) as Record<string, Json>
      return (
        propText(values.Name) === want.name &&
        propText(values.Stage) === want.stage &&
        propDate(values["Target Date"])?.start === want.date &&
        propText(values.Blocked) === want.blocked
      )
    }),
  )
  if (seededOk && pages.length === SEEDED.length) subscores.seeded_pages = 1
  else {
    diagnostics.push(
      `seeded rows mismatch — expected ${SEEDED.length} rows (${SEEDED.map((s) => s.name).join(", ")}); got ${
        pages.map((p) => propText((p.properties as Record<string, Json>)?.Name) ?? "(untitled)").join(", ") || "none"
      }`,
    )
  }

  // ---- the score: canonical comparison -------------------------------------
  const taskDir = (ctx?.taskDir as string | undefined) ?? import.meta.dirname
  const expectedIntents = await readJson<Json[]>(path.join(taskDir, "expected", "intents.json"))
  const diff = diffIntents(expectedIntents, intents)

  for (const group of diff.actual.ambiguities) {
    diagnostics.push(
      `note: structurally indistinguishable resources collapsed onto one label: ${group.join(", ")}`,
    )
  }

  if (diff.equal) {
    subscores.canonical = 1
    diagnostics.push("canonical intents match the oracle (up to resourceId renaming)")
    return { score: 1, subscores, diagnostics }
  }

  diagnostics.push(`canonical intents differ from the oracle (${diff.differences.length} difference(s)):`)
  for (const d of diff.differences.slice(0, MAX_REPORTED_DIFFS)) {
    diagnostics.push(`  [${d.kind}] ${d.path}: ${d.message}`)
  }
  if (diff.differences.length > MAX_REPORTED_DIFFS) {
    diagnostics.push(`  … and ${diff.differences.length - MAX_REPORTED_DIFFS} more`)
  }
  return { score: 0, subscores, diagnostics }
}
