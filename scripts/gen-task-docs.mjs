#!/usr/bin/env node
/**
 * Generate `docs/TASKS.md` — the long-form companion to `docs/COVERAGE.md`.
 *
 * COVERAGE.md is the matrix: one row per task, one line each, answering "is
 * this surface covered?". TASKS.md answers "what does this task actually ask
 * for, and what does the verifier look at?" — which is a paragraph per task,
 * and a paragraph per task rots the moment someone adds, renames or re-scopes
 * one. So it is generated, and regenerating it is a one-liner:
 *
 *   node scripts/gen-task-docs.mjs            # write docs/TASKS.md
 *   node scripts/gen-task-docs.mjs --check    # CI: fail if it is stale
 *   node scripts/gen-task-docs.mjs --stdout   # print, write nothing
 *
 * Everything in the output is derived from files that already exist:
 *
 *   PROMPT.md frontmatter  → id, title, suite, family, stage, difficulty,
 *                            runtime, fixture, verify layers, topics
 *   PROMPT.md body         → the plain-English summary (leading prose only;
 *                            the doc links to the prompt rather than copying it)
 *   EVAL.ts                → the subscore keys the verifier reports, and the
 *                            rule that turns them into the binary score
 *   wrong/ + live/wrong.*  → the foil's failure mode, when it is written down
 *   fixture/spec.json      → what a live trial gets provisioned with
 *
 * The only hand-written prose is the header block below (`HEADER`), which
 * explains what the file is and how scoring works. Everything else is
 * extracted, and anything that cannot be extracted reliably is reported as
 * "see EVAL.ts" rather than guessed at.
 *
 * Determinism is a requirement, not a nicety: no timestamps, no absolute
 * paths, stable sort (stage → family → id). Re-running with an unchanged
 * `evals/` produces a byte-identical file, so `--check` is a real CI gate.
 *
 * Plain Node, no dependencies — this must run before `pnpm install`.
 */
import { promises as fs } from "node:fs"
import * as path from "node:path"

const REPO_ROOT = path.resolve(import.meta.dirname, "..")
const EVALS_ROOT = path.join(REPO_ROOT, "evals")
const OUT_PATH = path.join(REPO_ROOT, "docs", "TASKS.md")
const OUT_REL = path.relative(REPO_ROOT, OUT_PATH).split(path.sep).join("/")
const REGEN_COMMAND = "node scripts/gen-task-docs.mjs"

/** Section order. `other` is the exhibition bucket and is rendered last. */
const STAGE_ORDER = ["build", "investigate", "resolve", "operate"]
const FAMILY_ORDER = ["cli", "workers", "nac", "ops"]

const STAGE_BLURB = {
  build: "Create something that does not exist yet.",
  investigate: "Diagnose from real state or logs and write the finding down.",
  resolve: "Fix something that is already broken.",
  operate: "Run the platform correctly — pacing, secrets, harnesses, audits.",
}

/** Only used to render the verify-layer glossary in the header. */
const VERIFY_GLOSSARY = [
  ["static", "the project typechecks / lints inside the sandbox"],
  ["exec-local", "`ntn workers exec --local` behavioural assertions"],
  ["intents", "canonical `dist/intents.json` compared against the oracle build"],
  ["state", "host-side assertions against the live workspace"],
  ["answer-file", "structured match against a file the agent wrote"],
  ["artifact", "exact match of a produced file"],
  ["timing", "wall-clock / pacing assertions"],
]

