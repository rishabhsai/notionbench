async function collectTasks() {
  const entries = await fs.readdir(EVALS_ROOT, { withFileTypes: true })
  const dirs = entries
    .filter((e) => e.isDirectory() && !e.name.startsWith(".") && !e.name.startsWith("_") && e.name !== "node_modules")
    .map((e) => path.join(EVALS_ROOT, e.name))
    .sort()

  const tasks = []
  for (const dir of dirs) {
    const promptPath = path.join(dir, "PROMPT.md")
    const prompt = await readIfPresent(promptPath)
    if (!prompt) continue
    const name = path.basename(dir)
    const { meta, body } = parsePrompt(prompt, name)
    if (meta.id !== name) throw new Error(`${name}: frontmatter id "${meta.id}" does not match the directory`)

    const evalSource = await readIfPresent(path.join(dir, "EVAL.ts"))
    if (!evalSource) throw new Error(`${name}: EVAL.ts is missing`)
    const stripped = stripComments(evalSource)

    tasks.push({
      meta,
      summary: summarize(body, name),
      checks: extractSubscoreKeys(stripped),
      scoreRule: extractScoreRule(stripped),
      foil: await extractFoil(dir),
      fixture: await describeFixture(dir, meta),
    })
  }
  return tasks
}

