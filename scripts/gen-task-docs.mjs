const CHECK_LIMIT = 14

function escapeCell(text) {
  return String(text).replace(/\|/g, "\\|")
}

function sortTasks(tasks) {
  return [...tasks].sort((a, b) => {
    const stage = STAGE_ORDER.indexOf(a.meta.stage) - STAGE_ORDER.indexOf(b.meta.stage)
    if (stage !== 0) return stage
    const family = FAMILY_ORDER.indexOf(a.meta.family) - FAMILY_ORDER.indexOf(b.meta.family)
    if (family !== 0) return family
    return a.meta.id < b.meta.id ? -1 : a.meta.id > b.meta.id ? 1 : 0
  })
}

function renderIndex(tasks) {
  const lines = [
    "## Index",
    "",
    "| id | suite | family | stage | runtime | what it asks for |",
    "|---|---|---|---|---|---|",
  ]
  for (const { meta } of tasks) {
    lines.push(
      `| [\`${meta.id}\`](#${meta.id}) | ${meta.suite} | ${meta.family} | ${meta.stage} | ${meta.runtime} | ${escapeCell(meta.title)} |`,
    )
  }
  lines.push("")
  return lines.join("\n")
}

function renderTask(task) {
  const { meta } = task
  const lines = []
  lines.push(`### ${meta.id}`)
  lines.push("")
  lines.push(`**${meta.title}**`)
  lines.push("")
  const facts = [
    `suite \`${meta.suite}\``,
    `family \`${meta.family}\``,
    `difficulty \`${meta.difficulty}\``,
    `runtime \`${meta.runtime}\``,
    `fixture \`${meta.fixture}\``,
    `verify ${meta.verify.map((v) => `\`${v}\``).join(" + ")}`,
  ]
  if (meta.topics.length > 0) facts.push(`topics ${meta.topics.map((t) => `\`${t}\``).join(", ")}`)
  lines.push(facts.join(" · "))
  lines.push("")
  lines.push(task.summary)
  lines.push("")
  lines.push(`- **Starting state.** ${task.fixture}`)

  if (task.checks && task.checks.length > 0) {
    const shown = task.checks.slice(0, CHECK_LIMIT).map((c) => `\`${c}\``)
    const overflow = task.checks.length - shown.length
    const tail = overflow > 0 ? `, +${overflow} more (see \`EVAL.ts\`)` : ""
    const rule = task.scoreRule ? ` — ${task.scoreRule}` : ""
    lines.push(`- **Checked.** ${shown.join(", ")}${tail}${rule}.`)
  } else {
    lines.push("- **Checked.** Not extractable from the verifier's shape — see `EVAL.ts`.")
  }

  if (task.foil) lines.push(`- **Foil's failure mode** (\`${task.foil.source}\`): ${task.foil.text}`)
  lines.push(
    `- **Files.** [PROMPT.md](../evals/${meta.id}/PROMPT.md) · [EVAL.ts](../evals/${meta.id}/EVAL.ts)`,
  )
  lines.push("")
  return lines.join("\n")
}

function render(tasks) {
  const scored = sortTasks(tasks.filter((t) => t.meta.suite !== "other"))
  const exhibition = sortTasks(tasks.filter((t) => t.meta.suite === "other"))

  const out = [HEADER, "", renderIndex([...scored, ...exhibition])]

  for (const stage of STAGE_ORDER) {
    const inStage = scored.filter((t) => t.meta.stage === stage)
    if (inStage.length === 0) continue
    const label = stage[0].toUpperCase() + stage.slice(1)
    out.push(`## ${label} (${inStage.length})`, "", STAGE_BLURB[stage], "")
    for (const task of inStage) out.push(renderTask(task))
  }

  if (exhibition.length > 0) {
    out.push(
      `## Exhibition (${exhibition.length}, unscored)`,
      "",
      "Outside the scored suite: the same open-ended prompt goes to every agent" +
        " configuration and the results are shown side by side. The verifier measures" +
        " the result and always returns 1, so nothing here moves a published number.",
      "",
    )
    for (const task of exhibition) out.push(renderTask(task))
  }

  return `${out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`
}

// ---------------------------------------------------------------------------

async function main() {
  const argv = process.argv.slice(2)
  const check = argv.includes("--check")
  const toStdout = argv.includes("--stdout")

  const tasks = await collectTasks()
  if (tasks.length === 0) throw new Error("no tasks found under evals/ — refusing to write an empty catalog")
  const output = render(tasks)

  if (toStdout) {
    process.stdout.write(output)
    return
  }
  if (check) {
    const current = await readIfPresent(OUT_PATH)
    if (current === output) {
      console.log(`${OUT_REL} is up to date (${tasks.length} tasks).`)
      return
    }
    console.error(`${OUT_REL} is stale — run \`${REGEN_COMMAND}\` and commit the result.`)
    process.exitCode = 1
    return
  }

  await fs.mkdir(path.dirname(OUT_PATH), { recursive: true })
  await fs.writeFile(OUT_PATH, output, "utf8")

  const missingChecks = tasks.filter((t) => !t.checks || t.checks.length === 0).map((t) => t.meta.id)
  const missingFoil = tasks.filter((t) => !t.foil).map((t) => t.meta.id)
  console.log(`wrote ${OUT_REL} — ${tasks.length} tasks`)
  if (missingChecks.length > 0) console.log(`  checks fell back to "see EVAL.ts": ${missingChecks.join(", ")}`)
  if (missingFoil.length > 0) console.log(`  no foil failure mode found (line omitted): ${missingFoil.join(", ")}`)
}

await main()
