// ---------------------------------------------------------------------------
// Frontmatter (a deliberately small YAML subset — see packages/core for the
// real parser; this script must run with no dependencies installed)
// ---------------------------------------------------------------------------

const REQUIRED_KEYS = ["id", "title", "suite", "family", "stage", "difficulty", "runtime", "fixture", "verify"]

function parseScalar(raw) {
  const text = raw.trim()
  if (text === "") return ""
  if (text.startsWith("[") && text.endsWith("]")) {
    return splitFlow(text.slice(1, -1)).map(parseScalar)
  }
  if (text.startsWith("{") && text.endsWith("}")) {
    const out = {}
    for (const part of splitFlow(text.slice(1, -1))) {
      const idx = part.indexOf(":")
      if (idx === -1) continue
      out[part.slice(0, idx).trim()] = parseScalar(part.slice(idx + 1))
    }
    return out
  }
  if ((text.startsWith('"') && text.endsWith('"')) || (text.startsWith("'") && text.endsWith("'"))) {
    return text.slice(1, -1)
  }
  if (text === "true") return true
  if (text === "false") return false
  if (text === "null" || text === "~") return null
  if (/^-?\d+(\.\d+)?$/.test(text)) return Number(text)
  return text
}

/** Split a flow collection body on top-level commas. */
function splitFlow(text) {
  const parts = []
  let depth = 0
  let quote = ""
  let current = ""
  for (const ch of text) {
    if (quote) {
      current += ch
      if (ch === quote) quote = ""
      continue
    }
    if (ch === '"' || ch === "'") {
      quote = ch
      current += ch
      continue
    }
    if (ch === "[" || ch === "{") depth++
    else if (ch === "]" || ch === "}") depth--
    if (ch === "," && depth === 0) {
      parts.push(current.trim())
      current = ""
      continue
    }
    current += ch
  }
  if (current.trim() !== "") parts.push(current.trim())
  return parts
}

/** Fold a `>-` block scalar the way YAML does: blank line = paragraph break. */
function foldBlock(lines) {
  const paragraphs = []
  let current = []
  for (const line of lines) {
    if (line.trim() === "") {
      if (current.length > 0) paragraphs.push(current.join(" "))
      current = []
    } else current.push(line.trim())
  }
  if (current.length > 0) paragraphs.push(current.join(" "))
  return paragraphs.join("\n\n")
}

function parsePrompt(text, source) {
  const normalized = text.replace(/^﻿/, "").replace(/\r\n/g, "\n")
  const lines = normalized.split("\n")
  if (!/^---[ \t]*$/.test(lines[0])) throw new Error(`${source}: missing YAML frontmatter block`)
  let end = -1
  for (let i = 1; i < lines.length; i++) {
    if (/^---[ \t]*$/.test(lines[i])) {
      end = i
      break
    }
  }
  if (end === -1) throw new Error(`${source}: unterminated frontmatter block`)

  const meta = {}
  const fm = lines.slice(1, end)
  for (let i = 0; i < fm.length; i++) {
    const line = fm[i]
    if (line.trim() === "" || line.trimStart().startsWith("#")) continue
    const m = /^([A-Za-z_][\w-]*):[ \t]*(.*)$/.exec(line)
    if (!m) continue // an indented continuation consumed by the block-scalar branch
    const [, key, rest] = m
    if (/^[|>][-+]?$/.test(rest.trim())) {
      const block = []
      while (i + 1 < fm.length && (fm[i + 1].trim() === "" || /^[ \t]/.test(fm[i + 1]))) {
        block.push(fm[++i])
      }
      meta[key] = rest.trim().startsWith(">") ? foldBlock(block) : block.map((l) => l.trim()).join("\n")
    } else {
      meta[key] = parseScalar(rest)
    }
  }

  for (const key of REQUIRED_KEYS) {
    if (meta[key] === undefined || meta[key] === "") {
      throw new Error(`${source}: frontmatter is missing \`${key}\``)
    }
  }
  if (!STAGE_ORDER.includes(meta.stage)) throw new Error(`${source}: unknown stage "${meta.stage}"`)
  if (!FAMILY_ORDER.includes(meta.family)) throw new Error(`${source}: unknown family "${meta.family}"`)
  if (!Array.isArray(meta.verify)) meta.verify = [meta.verify]
  if (!Array.isArray(meta.topics)) meta.topics = meta.topics === undefined ? [] : [meta.topics]

  const body = lines
    .slice(end + 1)
    .join("\n")
    .replace(/^(?:[ \t]*\n)+/, "")
  return { meta, body }
}

// ---------------------------------------------------------------------------
// Summary: the leading prose of the prompt, normalized. Never the whole prompt.
// ---------------------------------------------------------------------------

const SUMMARY_MIN = 200
const SUMMARY_MAX = 460

function isProse(paragraph) {
  return (
    !paragraph.startsWith("#") &&
    !paragraph.startsWith("```") &&
    !paragraph.startsWith(">") &&
    !/^[-*+]\s/.test(paragraph) &&
    !/^\d+[.)]\s/.test(paragraph)
  )
}

const SENTENCE_SPLIT = /(?<=[.!?:])[ \t]+/
/** A closer may follow the stop: `…thing.**`, `…this:` , `…(so).` */
const SENTENCE_END = /[.!?:]["'`)\]*_]*$/

function toSentences(text) {
  return text.split(SENTENCE_SPLIT)
}

/**
 * Trim to whole sentences under `max`, and drop a trailing fragment — prompts
 * routinely run a sentence into a bulleted list, and half a sentence reads as
 * an extraction bug. Ellipsis only when something was actually cut.
 */
function clipToSentences(text, max) {
  let out = ""
  let truncated = false
  for (const sentence of toSentences(text)) {
    const next = out === "" ? sentence : `${out} ${sentence}`
    if (next.length > max) {
      truncated = true
      break
    }
    out = next
  }
  if (!truncated && out !== "" && !SENTENCE_END.test(out)) {
    const kept = toSentences(out)
    if (kept.length > 1) {
      kept.pop()
      out = kept.join(" ")
      truncated = true
    }
  }
  if (out === "") {
    const hard = text.slice(0, max)
    out = hard.slice(0, hard.lastIndexOf(" "))
    truncated = true
  }
  return truncated ? `${out.trimEnd()} […]` : out.trim()
}

function summarize(body, source) {
  const cleaned = body.replace(/<!--[\s\S]*?-->/g, "")
  const paragraphs = cleaned
    .split(/\n[ \t]*\n/)
    .map((p) => p.trim())
    .filter(Boolean)

  const collected = []
  let total = 0
  for (const paragraph of paragraphs) {
    if (!isProse(paragraph)) {
      if (collected.length > 0) break
      continue
    }
    const normalized = paragraph.replace(/\s*\n\s*/g, " ").trim()
    collected.push(normalized)
    total += normalized.length
    if (total >= SUMMARY_MIN || collected.length >= 2) break
  }
  if (collected.length === 0) throw new Error(`${source}: no prose paragraph found in the prompt body`)
  return clipToSentences(collected.join(" "), SUMMARY_MAX)
}

// ---------------------------------------------------------------------------
// EVAL.ts: which subscores it reports, and the rule that makes them a score
// ---------------------------------------------------------------------------

/** Strip `//` and block comments, string- and template-literal aware. */
function stripComments(src) {
  let out = ""
  let i = 0
  while (i < src.length) {
    const ch = src[i]
    const next = src[i + 1]
    if (ch === "/" && next === "/") {
      while (i < src.length && src[i] !== "\n") i++
      continue
    }
    if (ch === "/" && next === "*") {
      i += 2
      while (i < src.length && !(src[i] === "*" && src[i + 1] === "/")) i++
      i += 2
      continue
    }
    if (ch === '"' || ch === "'" || ch === "`") {
      const quote = ch
      out += ch
      i++
      while (i < src.length) {
        if (src[i] === "\\") {
          out += src.slice(i, i + 2)
          i += 2
          continue
        }
        out += src[i]
        if (src[i] === quote) {
          i++
          break
        }
        i++
      }
      continue
    }
    out += ch
    i++
  }
  return out
}

const OPEN = { "{": "}", "[": "]", "(": ")" }

/** Slice the balanced bracket expression starting at `start` (inclusive). */
function balanced(src, start) {
  const close = OPEN[src[start]]
  if (!close) return undefined
  let depth = 0
  let quote = ""
  for (let i = start; i < src.length; i++) {
    const ch = src[i]
    if (quote) {
      if (ch === "\\") i++
      else if (ch === quote) quote = ""
      continue
    }
    if (ch === '"' || ch === "'" || ch === "`") {
      quote = ch
      continue
    }
    if (OPEN[ch]) depth++
    else if (ch === "}" || ch === "]" || ch === ")") {
      depth--
      if (depth === 0) return src.slice(start, i + 1)
    }
  }
  return undefined
}

/** Split an object-literal body on top-level commas. */
function splitEntries(body) {
  const entries = []
  let depth = 0
  let quote = ""
  let current = ""
  for (let i = 0; i < body.length; i++) {
    const ch = body[i]
    if (quote) {
      current += ch
      if (ch === "\\") current += body[++i] ?? ""
      else if (ch === quote) quote = ""
      continue
    }
    if (ch === '"' || ch === "'" || ch === "`") {
      quote = ch
      current += ch
      continue
    }
    if (OPEN[ch]) depth++
    else if (ch === "}" || ch === "]" || ch === ")") depth--
    if (ch === "," && depth === 0) {
      entries.push(current.trim())
      current = ""
      continue
    }
    current += ch
  }
  if (current.trim() !== "") entries.push(current.trim())
  return entries
}

/**
 * Resolve `Object.fromEntries(CASES.map((c) => [c.name, 0]))` by finding the
 * `CASES` array literal and reading the named field off each element.
 */
function resolveFromEntries(expr, src) {
  const m = /Object\.fromEntries\(\s*([A-Za-z_$][\w$]*)\s*\.map\(\s*\(?\s*([A-Za-z_$][\w$]*)/.exec(expr)
  if (!m) return undefined
  const [, arrayName, param] = m
  const field = new RegExp(`\\[\\s*${param}\\.([\\w$]+)`).exec(expr)?.[1]
  if (!field) return undefined

  const declaration = new RegExp(`\\b(?:const|let|var)\\s+${arrayName}\\b[^=\\n]*=\\s*\\[`).exec(src)
  if (!declaration) return undefined
  const literal = balanced(src, declaration.index + declaration[0].length - 1)
  if (!literal) return undefined

  // Element objects sit at brace depth 1 inside the array literal; only read
  // keys at that depth so a nested `{ name: … }` cannot smuggle in a subscore.
  const keys = []
  let depth = 0
  let quote = ""
  for (let i = 0; i < literal.length; i++) {
    const ch = literal[i]
    if (quote) {
      if (ch === "\\") i++
      else if (ch === quote) quote = ""
      continue
    }
    if (ch === '"' || ch === "'" || ch === "`") {
      quote = ch
      continue
    }
    if (ch === "{") depth++
    else if (ch === "}") depth--
    else if (depth === 1) {
      const rest = literal.slice(i)
      const hit = new RegExp(`^${field}\\s*:\\s*("([^"]*)"|'([^']*)')`).exec(rest)
      if (hit && !/[\w$]/.test(literal[i - 1] ?? "")) keys.push(hit[2] ?? hit[3])
    }
  }
  return keys.length > 0 ? keys : undefined
}

/** Keys of an object literal, resolving `...Object.fromEntries(...)` spreads. */
function literalKeys(literal, src) {
  const keys = []
  for (const entry of splitEntries(literal.slice(1, -1))) {
    if (entry.startsWith("...")) {
      const resolved = resolveFromEntries(entry, src)
      if (!resolved) return undefined
      keys.push(...resolved)
      continue
    }
    const m = /^(?:([A-Za-z_$][\w$]*)|"([^"]*)"|'([^']*)')\s*:/.exec(entry)
    if (!m) return undefined
    keys.push(m[1] ?? m[2] ?? m[3])
  }
  return keys
}

function extractSubscoreKeys(src) {
  const assignment = /subscores\s*:\s*Record<string,\s*number>\s*=\s*/.exec(src)
  if (assignment) {
    const start = assignment.index + assignment[0].length
    if (src[start] === "{") {
      const literal = balanced(src, start)
      if (literal) return literalKeys(literal, src)
    } else {
      const tail = src.slice(start, start + 400)
      const resolved = resolveFromEntries(tail, src)
      if (resolved) return resolved
    }
  }
  // A helper that builds the checklist instead: `function f(): Record<string,
  // number> { return { … } }`. Used by the exhibition placard.
  const helper = /\)\s*:\s*Record<string,\s*number>\s*\{/.exec(src)
  if (helper) {
    const returnAt = src.indexOf("return {", helper.index)
    if (returnAt !== -1) {
      const literal = balanced(src, src.indexOf("{", returnAt))
      if (literal) return literalKeys(literal, src)
    }
  }
  return undefined
}

/** How the subscores become the binary score, in one clause. */
function extractScoreRule(src) {
  const m = /const\s+score\s*=\s*([\s\S]*?)\n/.exec(src)
  if (m) {
    const expr = m[1]
    if (/Object\.values\(subscores\)\.every/.test(expr)) return "every subscore must be 1"
    const gates = [...expr.matchAll(/subscores\.([\w$]+)/g)].map((g) => g[1])
    if (gates.length > 0) {
      return `gated on ${[...new Set(gates)].map((g) => `\`${g}\``).join(" and ")}`
    }
  }
  if (/\breturn\s*\{\s*score:\s*1\b/.test(src) && !/\bscore:\s*0\b/.test(src)) {
    return "reported as a checklist only; the score is always 1, unscored by construction"
  }
  if (/diffIntents/.test(src)) {
    return "the canonical intents diff against the oracle build is the score; subscores localize the difference"
  }
  return undefined
}

// ---------------------------------------------------------------------------
// The `wrong/` foil's failure mode, when the repo writes it down
