function countComments(spec) {
  let threads = 0
  for (const page of spec.pages ?? []) {
    threads += (page.comments ?? []).length
    for (const block of page.blocks ?? []) threads += (block.comments ?? []).length
  }
  return threads
}

function countRows(database) {
  const rows = database.rows
  if (Array.isArray(rows)) return rows.length
  if (rows && typeof rows.count === "number") return rows.count
  return 0
}

function plural(n, one, many = `${one}s`) {
  return `${n} ${n === 1 ? one : many}`
}

function describeSpec(spec) {
  const databases = spec.databases ?? []
  const parts = []
  if ((spec.pages ?? []).length > 0) parts.push(plural(spec.pages.length, "page"))
  if (databases.length > 0) {
    const rows = databases.reduce((sum, db) => sum + countRows(db), 0)
    parts.push(
      rows === 0
        ? `${plural(databases.length, "empty database")}`
        : `${plural(databases.length, "database")} holding ${plural(rows, "row")}`,
    )
  }
  const views = databases.reduce((sum, db) => sum + (db.views ?? []).length, 0)
  if (views > 0) parts.push(`${plural(views, "extra saved view")}`)
  if ((spec.files ?? []).length > 0) parts.push(plural(spec.files.length, "uploaded file"))
  const comments = countComments(spec)
  if (comments > 0) parts.push(plural(comments, "comment thread"))

  const provisioned = parts.length > 0 ? parts.join(", ") : "an empty sandbox root"
  const seed = typeof spec.seed === "number" ? `, seeded \`${spec.seed}\`` : ""
  return `a per-trial sandbox root page containing ${provisioned}${seed}`
}

async function countWorkspaceFiles(dir) {
  let count = 0
  for await (const file of walkFiles(dir)) {
    if (path.basename(file) === ".gitkeep") continue
    count++
  }
  return count
}

async function describeFixture(taskDir, meta) {
  const spec = await readIfPresent(path.join(taskDir, "fixture", "spec.json"))
  if (spec) {
    let parsed
    try {
      parsed = JSON.parse(spec)
    } catch {
      return "`fixture/spec.json` is present but unreadable — see the file."
    }
    return `Provisioned from \`fixture/spec.json\` into ${describeSpec(parsed)}.`
  }
  const workspace = path.join(taskDir, "fixture", "workspace")
  const files = await countWorkspaceFiles(workspace)
  if (files > 0) {
    return `\`fixture/workspace/\` (${plural(files, "file")}) is copied into the sandbox as the starting project.`
  }
  if (meta.runtime === "live") {
    return "No fixture spec — the trial starts from an empty per-trial sandbox page."
  }
  return "No fixture — the trial starts from an empty sandbox."
}

