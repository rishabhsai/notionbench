const FOIL_MAX = 300

/** Leading `/** … *\/` banner of a file, as plain text. */
function leadingBanner(text) {
  const m = /^\s*\/\*\*([\s\S]*?)\*\//.exec(text)
  if (!m) return undefined
  return m[1]
    .split("\n")
    .map((line) => line.replace(/^[ \t]*\*[ \t]?/, ""))
    .join("\n")
}

/** A run of consecutive `//` lines starting at a recognized opener. */
function commentBlock(text) {
  const lines = text.split("\n")
  const opener = lines.findIndex((line) =>
    /^\s*\/\/\s*(A plausible|The plausible|A plausibly|The bug\b|The mistake\b)/i.test(line),
  )
  if (opener === -1) return undefined
  const block = []
  for (let i = opener; i < lines.length; i++) {
    const m = /^\s*\/\/\s?(.*)$/.exec(lines[i])
    if (!m) break
    block.push(m[1])
  }
  return block.join("\n")
}

function tidyFoil(text) {
  let out = text
    .replace(/^[\s\S]*?Plausibly-wrong solution for [\w-]+\s*/i, "")
    .replace(/^[\s\S]*?(?:A plausible-but-wrong|The plausible)\b[^:—-]*[:—-]\s*/i, "")
    .replace(/^\s*The (?:bug|mistake)\s*:\s*/i, "")
    .replace(/\s*Must score 0\.?\s*$/i, "")
    .split(/\n[ \t]*\n/)
    .map((p) => p.replace(/\s*\n\s*/g, " ").trim())
    .filter(Boolean)
    .join(" ")
    .replace(/^[\s:—–-]+/, "")
    .trim()
  // Drop QC-plumbing asides; they explain the harness, not the failure.
  out = out.split(/(?<=[.!?])\s+/).filter((s) => !/fake-notion|QC time|QC only/i.test(s)).join(" ")
  if (out === "") return undefined
  return clipToSentences(out, FOIL_MAX)
}

async function readIfPresent(file) {
  try {
    return await fs.readFile(file, "utf8")
  } catch {
    return undefined
  }
}

async function* walkFiles(dir) {
  let entries
  try {
    entries = await fs.readdir(dir, { withFileTypes: true })
  } catch {
    return
  }
  for (const entry of entries.sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      if (entry.name === "node_modules") continue
      yield* walkFiles(full)
    } else yield full
  }
}

async function extractFoil(taskDir) {
  const rel = (p) => path.relative(taskDir, p).split(path.sep).join("/")

  const wrongMjs = path.join(taskDir, "live", "wrong.mjs")
  const mjs = await readIfPresent(wrongMjs)
  if (mjs) {
    const banner = leadingBanner(mjs)
    const text = banner ? tidyFoil(banner) : undefined
    // Some foils are a loader for a sibling worker; the bug is described there.
    if (text && !/wrong\.worker\.ts/.test(text)) return { source: rel(wrongMjs), text }
    const workerPath = path.join(taskDir, "live", "wrong.worker.ts")
    const worker = await readIfPresent(workerPath)
    const fromWorker = worker ? tidyFoil(commentBlock(worker) ?? "") : undefined
    if (fromWorker) return { source: rel(workerPath), text: fromWorker }
    if (text) return { source: rel(wrongMjs), text }
  }

  const readme = await readIfPresent(path.join(taskDir, "wrong", "README.md"))
  if (readme) {
    const text = tidyFoil(readme.replace(/^#.*$/m, ""))
    if (text) return { source: "wrong/README.md", text }
  }

  for await (const file of walkFiles(path.join(taskDir, "wrong"))) {
    if (!/\.(ts|tsx|mts|mjs|js)$/.test(file)) continue
    const source = await readIfPresent(file)
    if (!source) continue
    const block = commentBlock(source) ?? leadingBanner(source)
    const text = block ? tidyFoil(block) : undefined
    if (text) return { source: rel(file), text }
  }
  return undefined
}

